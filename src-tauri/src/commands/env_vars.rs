#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("cairn-env-{}-{}", name, std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn write_env_file_prepends_the_marker() {
        let dir = temp_dir("marker");
        let path = dir.to_string_lossy().to_string();

        assert!(write_env_file(path.clone(), ".env".into(), "A=1".into(), None).unwrap());

        let content = fs::read_to_string(dir.join(".env")).unwrap();
        assert_eq!(content, format!("{ENV_FILE_MARKER}\nA=1\n"));
    }

    #[test]
    fn write_env_file_refuses_a_foreign_file() {
        let dir = temp_dir("foreign");
        let path = dir.to_string_lossy().to_string();
        fs::write(dir.join(".env"), "A=kept\n").unwrap();

        assert!(!write_env_file(path.clone(), ".env".into(), "A=1".into(), None).unwrap());
        assert_eq!(fs::read_to_string(dir.join(".env")).unwrap(), "A=kept\n");

        let status = env_file_status(path.clone(), ".env".into()).unwrap();
        assert!(status.exists);
        assert!(!status.managed);
    }

    #[test]
    fn write_env_file_takes_a_foreign_file_over_when_forced() {
        let dir = temp_dir("takeover");
        let path = dir.to_string_lossy().to_string();
        fs::write(dir.join(".env"), "A=kept\n").unwrap();

        assert!(write_env_file(path.clone(), ".env".into(), "A=1".into(), Some(true)).unwrap());

        assert!(env_file_status(path, ".env".into()).unwrap().managed);
    }

    #[test]
    fn write_env_file_rewrites_its_own_file() {
        let dir = temp_dir("idempotent");
        let path = dir.to_string_lossy().to_string();

        write_env_file(path.clone(), ".env".into(), "A=1".into(), None).unwrap();
        assert!(write_env_file(path.clone(), ".env".into(), "A=2".into(), None).unwrap());

        let content = fs::read_to_string(dir.join(".env")).unwrap();
        assert_eq!(content, format!("{ENV_FILE_MARKER}\nA=2\n"));
        assert!(env_file_status(path, ".env".into()).unwrap().managed);
    }

    #[test]
    fn delete_env_file_only_removes_a_generated_file() {
        let dir = temp_dir("delete");
        let path = dir.to_string_lossy().to_string();
        fs::write(dir.join(".env"), "A=kept\n").unwrap();

        assert!(!delete_env_file(path.clone(), ".env".into()).unwrap());
        assert!(dir.join(".env").is_file());

        write_env_file(path.clone(), ".env.local".into(), "A=1".into(), None).unwrap();
        assert!(delete_env_file(path, ".env.local".into()).unwrap());
        assert!(!dir.join(".env.local").is_file());
    }

    #[test]
    fn resolve_target_rejects_a_name_leaving_the_worktree() {
        assert!(resolve_target("/tmp", "../escaped").is_err());
        assert!(resolve_target("/tmp", "sub/.env").is_err());
        assert!(resolve_target("/tmp", "  ").is_err());
    }
}
