// Generated file in the worktree
// ---------------------------------------------------------------------------

#[tauri::command]
pub fn env_file_status(worktree_path: String, file_name: String) -> Result<EnvFileStatus, String> {
    let target = resolve_target(&worktree_path, &file_name)?;
    if !target.is_file() {
        return Ok(EnvFileStatus { exists: false, managed: false });
    }
    Ok(EnvFileStatus { exists: true, managed: is_managed(&target) })
}

#[tauri::command]
pub fn read_env_file(worktree_path: String, file_name: String) -> Result<String, String> {
    let target = resolve_target(&worktree_path, &file_name)?;
    if !target.is_file() { return Ok(String::new()); }
    fs::read_to_string(&target).map_err(|e| e.to_string())
}

#[tauri::command]
pub fn write_env_file(
    worktree_path: String,
    file_name: String,
    body: String,
    force: Option<bool>,
) -> Result<bool, String> {
    let target = resolve_target(&worktree_path, &file_name)?;
    if target.is_file() && !is_managed(&target) && !force.unwrap_or(false) {
        return Ok(false);
    }
    let mut content = String::from(ENV_FILE_MARKER);
    content.push('\n');
    if !body.is_empty() {
        content.push_str(&body);
        if !body.ends_with('\n') { content.push('\n'); }
    }
    if fs::read_to_string(&target).map(|existing| existing == content).unwrap_or(false) {
        return Ok(true);
    }
    fs::write(&target, content).map_err(|e| e.to_string())?;
    Ok(true)
}

#[tauri::command]
pub fn delete_env_file(worktree_path: String, file_name: String) -> Result<bool, String> {
    let target = resolve_target(&worktree_path, &file_name)?;
    if !target.is_file() || !is_managed(&target) { return Ok(false); }
    fs::remove_file(&target).map_err(|e| e.to_string())?;
    Ok(true)
}

#[tauri::command]
pub async fn ensure_env_ignored(worktree_path: String, file_name: String) -> Result<bool, String> {
    let dir = shellexpand::tilde(&worktree_path).into_owned();
    if !Path::new(&dir).is_dir() { return Ok(false); }

    let already = Command::new("git")
        .current_dir(&dir)
        .args(["check-ignore", "-q", "--", &file_name])
        .status()
        .map_err(|e| e.to_string())?
        .success();
    if already { return Ok(false); }

    let out = Command::new("git")
        .current_dir(&dir)
        .args(["rev-parse", "--path-format=absolute", "--git-common-dir"])
        .output()
        .map_err(|e| e.to_string())?;
    if !out.status.success() { return Ok(false); }
    let common = String::from_utf8_lossy(&out.stdout).trim().to_string();
    if common.is_empty() { return Ok(false); }

    let exclude = Path::new(&common).join("info").join("exclude");
    if let Some(parent) = exclude.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let existing = fs::read_to_string(&exclude).unwrap_or_default();
    if existing.lines().any(|l| l.trim() == file_name) { return Ok(false); }

    let mut next = existing;
    if !next.is_empty() && !next.ends_with('\n') { next.push('\n'); }
    next.push_str(&format!("{file_name}\n"));
    fs::write(&exclude, next).map_err(|e| e.to_string())?;
    Ok(true)
}

