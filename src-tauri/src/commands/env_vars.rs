use std::collections::HashMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use serde::{Deserialize, Serialize};
use crate::storage::{
    global_env_file, instance_env_file, project_env_file, write_json_atomic,
};

pub const ENV_FILE_MARKER: &str = "# Generated by Cairn - edits are overwritten";

fn default_true() -> bool { true }

fn default_env_file_name() -> String { ".env".to_string() }

#[derive(Serialize, Deserialize, Clone)]
pub struct EnvVariable {
    pub id: String,
    pub key: String,
    #[serde(default)]
    pub value: String,
    #[serde(rename = "perInstance", default)]
    pub per_instance: bool,
    #[serde(default)]
    pub secret: bool,
    #[serde(default = "default_true")]
    pub enabled: bool,
}

#[derive(Serialize, Deserialize, Clone)]
pub struct EnvFile {
    #[serde(default)]
    pub variables: Vec<EnvVariable>,
    #[serde(default)]
    pub overrides: HashMap<String, String>,
    #[serde(rename = "writeEnvFile", default = "default_true")]
    pub write_env_file: bool,
    #[serde(rename = "envFileName", default = "default_env_file_name")]
    pub env_file_name: String,
}

impl Default for EnvFile {
    fn default() -> Self {
        Self {
            variables: Vec::new(),
            overrides: HashMap::new(),
            write_env_file: true,
            env_file_name: default_env_file_name(),
        }
    }
}

#[derive(Serialize, Deserialize, Clone, Default)]
pub struct EnvFileStatus {
    pub exists: bool,
    pub managed: bool,
}

fn read_env(path: &Path) -> Result<EnvFile, String> {
    if !path.exists() { return Ok(EnvFile::default()); }
    let content = fs::read_to_string(path).map_err(|e| e.to_string())?;
    serde_json::from_str(&content).map_err(|e| e.to_string())
}

fn resolve_target(worktree_path: &str, file_name: &str) -> Result<PathBuf, String> {
    let name = file_name.trim();
    let invalid = name.is_empty()
        || name == "."
        || name == ".."
        || name.contains('/')
        || name.contains('\\');
    if invalid {
        return Err(format!("Invalid env file name: {file_name}"));
    }
    let dir = shellexpand::tilde(worktree_path).into_owned();
    Ok(Path::new(&dir).join(name))
}

fn is_managed(path: &Path) -> bool {
    let Ok(content) = fs::read_to_string(path) else { return false };
    content.lines().next().map(|l| l.trim_end() == ENV_FILE_MARKER).unwrap_or(false)
}

